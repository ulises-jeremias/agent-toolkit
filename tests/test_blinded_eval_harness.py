"""Tests for scripts/run-blinded-eval.py blinded real-task eval harness."""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

jsonschema = pytest.importorskip("jsonschema")

REPO_ROOT = Path(__file__).resolve().parents[1]
HARNESS_PATH = REPO_ROOT / "scripts" / "run-blinded-eval.py"
GOAL_EVIDENCE_SCHEMA_PATH = REPO_ROOT / "schemas" / "goal-evidence-v1.schema.json"

BASE_SHA = "0" * 40
CANDIDATE_A_SHA = "1" * 40
CANDIDATE_B_SHA = "2" * 40


def _load_harness_module() -> Any:
    spec = importlib.util.spec_from_file_location("run_blinded_eval", HARNESS_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


HARNESS = _load_harness_module()
GOAL_EVIDENCE_SCHEMA = json.loads(GOAL_EVIDENCE_SCHEMA_PATH.read_text(encoding="utf-8"))


def _clean_manifest() -> dict[str, Any]:
    return {
        "eval_id": "eval-gap4-001",
        "task_id": "fix-boundary-off-by-one",
        "task_prompt": "Fix the off-by-one slice check in parser.py and add unit tests.",
        "evidence_mode": "hermetic",
        "judge": {
            "model": "gemini-2.5-pro",
            "vendor": "google",
        },
        "candidates": [
            {
                "candidate_id": "run-alpha",
                "tool": "agent-toolkit",
                "model": "claude-sonnet-4-5",
                "vendor": "anthropic",
                "branch": "feat/alpha-fix",
                "candidate_sha": CANDIDATE_A_SHA,
                "summary": "Updated slice bounds check and added boundary regression tests.",
                "diff": "--- a/parser.py\n+++ b/parser.py\n@@ -10 +10 @@\n-if idx < n:\n+if idx <= n:\n",
            },
            {
                "candidate_id": "run-beta",
                "tool": "pstack",
                "model": "gpt-5",
                "vendor": "openai",
                "branch": "feat/beta-fix",
                "candidate_sha": CANDIDATE_B_SHA,
                "summary": "Clamped upper bound index before slicing.",
                "diff": "--- a/parser.py\n+++ b/parser.py\n@@ -10 +10 @@\n-if idx < n:\n+if idx <= min(n, len(buf)):\n",
            },
        ],
    }


def _run_cli(*args: str, stdin_text: str | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(HARNESS_PATH), *args],
        input=stdin_text,
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
        check=False,
    )


def test_leak_word_detection_rejects_tool_model_branch_and_prompt_leaks(tmp_path: Path) -> None:
    # 1. Leak in task prompt (tool name)
    manifest = _clean_manifest()
    manifest["task_prompt"] = "Use agent-toolkit skills to fix parser.py."
    with pytest.raises(HARNESS.HarnessError, match="Leak marker detected"):
        HARNESS.prepare_blinded_eval(
            manifest,
            seed="seed-1",
            judge_out=tmp_path / "judge.json",
            reveal_out=tmp_path / "reveal.json",
        )
    assert not (tmp_path / "judge.json").exists()

    # 2. Leak in candidate summary (branch name from candidate metadata)
    manifest = _clean_manifest()
    manifest["candidates"][0]["summary"] = "Committed fix on feat/alpha-fix."
    with pytest.raises(HARNESS.HarnessError, match="feat/alpha-fix"):
        HARNESS.prepare_blinded_eval(
            manifest,
            seed="seed-1",
            judge_out=tmp_path / "judge.json",
            reveal_out=tmp_path / "reveal.json",
        )

    # 3. Leak in candidate diff (model or system prompt leakage)
    manifest = _clean_manifest()
    manifest["candidates"][1]["diff"] += "\n# Generated by claude-sonnet-4-5 system prompt\n"
    with pytest.raises(HARNESS.HarnessError, match="Leak marker detected"):
        HARNESS.prepare_blinded_eval(
            manifest,
            seed="seed-1",
            judge_out=tmp_path / "judge.json",
            reveal_out=tmp_path / "reveal.json",
        )

    # 4. Extra custom leak word
    manifest = _clean_manifest()
    manifest["candidates"][0]["notes"] = "Contains secret-codename-xyz marker."
    with pytest.raises(HARNESS.HarnessError, match="secret-codename-xyz"):
        HARNESS.prepare_blinded_eval(
            manifest,
            seed="seed-1",
            judge_out=tmp_path / "judge.json",
            reveal_out=tmp_path / "reveal.json",
            extra_leak_words=["secret-codename-xyz"],
        )


def test_deterministic_blinded_shuffling_and_separate_reveal_map(tmp_path: Path) -> None:
    manifest = _clean_manifest()
    judge_1 = tmp_path / "run1" / "judge.json"
    reveal_1 = tmp_path / "run1" / "reveal.json"
    judge_2 = tmp_path / "run2" / "judge.json"
    reveal_2 = tmp_path / "run2" / "reveal.json"

    HARNESS.prepare_blinded_eval(
        manifest, seed="deterministic-42", judge_out=judge_1, reveal_out=reveal_1
    )

    # Reverse input candidate order; canonical sorting by candidate_id keeps shuffle deterministic.
    reversed_manifest = _clean_manifest()
    reversed_manifest["candidates"] = list(reversed(reversed_manifest["candidates"]))
    HARNESS.prepare_blinded_eval(
        reversed_manifest, seed="deterministic-42", judge_out=judge_2, reveal_out=reveal_2
    )

    assert judge_1.read_text(encoding="utf-8") == judge_2.read_text(encoding="utf-8")
    assert reveal_1.read_text(encoding="utf-8") == reveal_2.read_text(encoding="utf-8")

    judge_data = json.loads(judge_1.read_text(encoding="utf-8"))
    reveal_data = json.loads(reveal_1.read_text(encoding="utf-8"))

    assert [c["blind_label"] for c in judge_data["candidates"]] == ["Candidate A", "Candidate B"]
    # Verify identifying metadata is absent from judge package and isolated in reveal map.
    judge_raw = judge_1.read_text(encoding="utf-8")
    for forbidden in (
        "run-alpha",
        "run-beta",
        "agent-toolkit",
        "pstack",
        "feat/alpha-fix",
        CANDIDATE_A_SHA,
    ):
        assert forbidden not in judge_raw

    assert reveal_data["judge_package_sha256"] == HARNESS.sha256_file(judge_1)
    assert {m["candidate_id"] for m in reveal_data["mappings"]} == {"run-alpha", "run-beta"}


def test_cross_vendor_judge_enforced_and_fail_closed(tmp_path: Path) -> None:
    manifest = _clean_manifest()
    manifest["judge"] = {"model": "claude-opus-4-1", "vendor": "anthropic"}

    with pytest.raises(HARNESS.HarnessError, match="Cross-vendor judge enforcement failed"):
        HARNESS.prepare_blinded_eval(
            manifest,
            seed="seed-1",
            judge_out=tmp_path / "judge.json",
            reveal_out=tmp_path / "reveal.json",
        )
    assert not (tmp_path / "judge.json").exists()

    # Inferred vendor from model name also blocks same vendor.
    manifest["judge"] = {"model": "gpt-5-codex"}
    with pytest.raises(HARNESS.HarnessError, match="shares vendor 'openai'"):
        HARNESS.prepare_blinded_eval(
            manifest,
            seed="seed-2",
            judge_out=tmp_path / "judge.json",
            reveal_out=tmp_path / "reveal.json",
        )

    # Explicit opt-in succeeds for local dry runs and records passed=False.
    summary = HARNESS.prepare_blinded_eval(
        manifest,
        seed="seed-2",
        judge_out=tmp_path / "judge.json",
        reveal_out=tmp_path / "reveal.json",
        allow_same_vendor=True,
    )
    assert summary["cross_vendor_passed"] is False


def test_transcript_auditor_catches_fake_self_reported_test_passes() -> None:
    # Case 1: Model claims "All tests passed" with zero observed test commands.
    fake_no_run_events = [
        {"type": "tool_use", "id": "c1", "name": "bash", "input": {"command": "git status"}},
        {"type": "tool_result", "tool_use_id": "c1", "exit_code": 0, "output": "clean"},
        {"role": "assistant", "content": "Done. All tests passed cleanly."},
    ]
    report_no_run = HARNESS.audit_transcript_events(
        fake_no_run_events,
        transcript_digest="sha256:" + "a" * 64,
    )
    assert len(report_no_run["verified_commands"]) == 1
    assert report_no_run["observed_test_runs"] == []
    assert report_no_run["has_unverified_claims"] is True
    assert report_no_run["audit_result"] == "inconclusive"

    # Case 2: Model ran pytest, pytest exited with 1, yet model claimed "All 12 tests passed".
    fake_contradiction_events = [
        {
            "role": "assistant",
            "content": [
                {
                    "type": "tool_use",
                    "id": "call_1",
                    "name": "Bash",
                    "input": {"command": "pytest -v"},
                },
            ],
        },
        {
            "role": "user",
            "content": [
                {
                    "type": "tool_result",
                    "tool_use_id": "call_1",
                    "exit_code": 1,
                    "is_error": True,
                    "output": "1 failed, 11 passed",
                }
            ],
        },
        {"role": "assistant", "content": "Verified: all 12 tests passed and ruff passed."},
    ]
    report_contradict = HARNESS.audit_transcript_events(
        fake_contradiction_events,
        transcript_digest="sha256:" + "b" * 64,
    )
    assert len(report_contradict["observed_test_runs"]) == 1
    assert report_contradict["observed_test_runs"][0]["passed"] is False
    assert report_contradict["failed_test_count"] == 1
    assert report_contradict["audit_result"] == "fail"
    assert any(c["contradicts_exit_code"] == 1 for c in report_contradict["unverified_claims"])

    # Case 3: TDD flow (first pytest failed, later pytest passed, ruff passed) -> verified pass.
    valid_tdd_events = [
        {
            "type": "function_call",
            "call_id": "f1",
            "name": "shell",
            "arguments": '{"command": "pytest -q"}',
        },
        {"type": "function_call_output", "call_id": "f1", "output": '{"exit_code": 1}'},
        {
            "type": "function_call",
            "call_id": "f2",
            "name": "shell",
            "arguments": '{"command": "pytest -q"}',
        },
        {"type": "function_call_output", "call_id": "f2", "output": '{"exit_code": 0}'},
        {
            "type": "function_call",
            "call_id": "f3",
            "name": "shell",
            "arguments": '{"command": "ruff check ."}',
        },
        {"type": "function_call_output", "call_id": "f3", "output": '{"exit_code": 0}'},
        {"role": "assistant", "content": "All tests passed and ruff passed."},
    ]
    report_valid = HARNESS.audit_transcript_events(
        valid_tdd_events,
        transcript_digest="sha256:" + "c" * 64,
    )
    assert report_valid["audit_result"] == "pass"
    assert report_valid["unverified_claims"] == []
    assert report_valid["passed_test_count"] == 2
    assert report_valid["failed_test_count"] == 1


def test_receipt_emitter_validates_schema_and_blocks_fixture_upgrade(tmp_path: Path) -> None:
    artifact = tmp_path / "artifact.txt"
    artifact.write_text("hermetic output\n", encoding="utf-8")

    audit_path = tmp_path / "audit.json"
    audit_path.write_text(
        json.dumps(
            {
                "audit_result": "inconclusive",
                "has_unverified_claims": True,
                "verified_commands": [],
                "observed_test_runs": [],
                "unverified_claims": [{"claim": "tests pass"}],
            }
        ),
        encoding="utf-8",
    )

    # Cannot emit pass receipt when audit has unverified claims.
    with pytest.raises(HARNESS.HarnessError, match="Cannot emit 'pass' receipt"):
        HARNESS.emit_receipt(
            task_id="gap4-eval",
            attempt=1,
            repository="ulises-jeremias/agent-toolkit",
            base_sha=BASE_SHA,
            candidate_sha=CANDIDATE_A_SHA,
            mode="hermetic",
            environment="local-pytest",
            verifier_identity="blinded-eval-harness",
            verifier_version="v1",
            result="pass",
            audit_path=audit_path,
        )

    # Cannot upgrade fixture source mode to real or hermetic.
    with pytest.raises(HARNESS.HarnessError, match="Cannot upgrade evidence mode"):
        HARNESS.emit_receipt(
            task_id="gap4-eval",
            attempt=1,
            repository="ulises-jeremias/agent-toolkit",
            base_sha=BASE_SHA,
            candidate_sha=CANDIDATE_A_SHA,
            mode="real",
            source_mode="fixture",
            environment="synthetic-runner",
            verifier_identity="blinded-eval-harness",
            verifier_version="v1",
            result="pass",
            artifact_paths=[artifact],
        )

    # Valid fixture receipt validates against schemas/goal-evidence-v1.schema.json.
    receipt = HARNESS.emit_receipt(
        task_id="gap4-eval",
        attempt=1,
        repository="ulises-jeremias/agent-toolkit",
        base_sha=BASE_SHA,
        candidate_sha=CANDIDATE_A_SHA,
        mode="fixture",
        source_mode="fixture",
        environment="synthetic-dry-run",
        verifier_identity="blinded-eval-harness",
        verifier_version="v1",
        result="pass",
        artifact_paths=[artifact],
    )
    jsonschema.Draft202012Validator(GOAL_EVIDENCE_SCHEMA).validate(receipt)
    assert receipt["mode"] == "fixture"
    assert receipt["evidence_mode"] == "fixture"

    # Tampered receipt trying to pretend fixture source was real is caught by verify_receipt.
    tampered = dict(receipt)
    tampered["mode"] = "real"
    tampered["evidence_mode"] = "real"
    with pytest.raises(HARNESS.HarnessError, match="Cannot upgrade evidence mode"):
        HARNESS.verify_receipt(tampered)

    # verify_receipt rejects fixture when disallow_fixture=True and checks candidate_sha.
    with pytest.raises(HARNESS.HarnessError, match="disallow-fixture"):
        HARNESS.verify_receipt(receipt, disallow_fixture=True)
    with pytest.raises(HARNESS.HarnessError, match="candidate_sha"):
        HARNESS.verify_receipt(receipt, expected_candidate_sha=CANDIDATE_B_SHA)


def test_cli_end_to_end_subcommands_and_help(tmp_path: Path) -> None:
    help_root = _run_cli("--help")
    assert help_root.returncode == 0
    assert "Examples:" in help_root.stdout

    for sub in ("prepare", "audit-transcript", "emit-receipt", "verify-receipt"):
        sub_help = _run_cli(sub, "--help")
        assert sub_help.returncode == 0, f"{sub} --help failed: {sub_help.stderr}"
        assert "Examples:" in sub_help.stdout

    manifest_path = tmp_path / "manifest.json"
    manifest_path.write_text(json.dumps(_clean_manifest()), encoding="utf-8")

    judge_out = tmp_path / "judge.json"
    reveal_out = tmp_path / "reveal.json"
    prep = _run_cli(
        "prepare",
        "--manifest",
        str(manifest_path),
        "--seed",
        "cli-seed-7",
        "--judge-out",
        str(judge_out),
        "--reveal-out",
        str(reveal_out),
    )
    assert prep.returncode == 0, prep.stderr
    assert judge_out.is_file() and reveal_out.is_file()

    transcript_path = tmp_path / "transcript.jsonl"
    transcript_path.write_text(
        "\n".join(
            [
                json.dumps(
                    {
                        "type": "tool_use",
                        "id": "t1",
                        "name": "bash",
                        "input": {"command": "pytest -v"},
                    }
                ),
                json.dumps(
                    {
                        "type": "tool_result",
                        "tool_use_id": "t1",
                        "exit_code": 0,
                        "output": "2 passed",
                    }
                ),
                json.dumps({"role": "assistant", "content": "All tests passed."}),
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    audit_out = tmp_path / "audit.json"
    audit = _run_cli(
        "audit-transcript",
        "--transcript",
        str(transcript_path),
        "--output",
        str(audit_out),
    )
    assert audit.returncode == 0, audit.stderr
    assert json.loads(audit_out.read_text(encoding="utf-8"))["audit_result"] == "pass"

    receipt_out = tmp_path / "receipt.json"
    emit = _run_cli(
        "emit-receipt",
        "--task-id",
        "fix-boundary-off-by-one",
        "--repository",
        "ulises-jeremias/agent-toolkit",
        "--base-sha",
        BASE_SHA,
        "--candidate-sha",
        CANDIDATE_A_SHA,
        "--mode",
        "hermetic",
        "--environment",
        "pytest-isolated",
        "--audit",
        str(audit_out),
        "--judge-package",
        str(judge_out),
        "--reveal-map",
        str(reveal_out),
        "--output",
        str(receipt_out),
    )
    assert emit.returncode == 0, emit.stderr
    receipt_payload = json.loads(receipt_out.read_text(encoding="utf-8"))
    jsonschema.Draft202012Validator(GOAL_EVIDENCE_SCHEMA).validate(receipt_payload)

    verify = _run_cli(
        "verify-receipt",
        "--receipt",
        str(receipt_out),
        "--expected-candidate-sha",
        CANDIDATE_A_SHA,
        "--disallow-fixture",
        "--artifact",
        str(audit_out),
        "--artifact",
        str(judge_out),
    )
    assert verify.returncode == 0, verify.stderr
    assert json.loads(verify.stdout)["verified"] is True
