export type PixelIconName = keyof typeof ICONS;

interface Run {
  x: number;
  y: number;
  width: number;
  dim: boolean;
}

function runs(rows: readonly string[]): Run[] {
  const out: Run[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const cell = row[x];
      if (cell !== '#' && cell !== 'o') {
        x += 1;
        continue;
      }
      let width = 1;
      while (row[x + width] === cell) width += 1;
      out.push({ x, y, width, dim: cell === 'o' });
      x += width;
    }
  });
  return out;
}

const CACHE = new Map<PixelIconName, Run[]>();

export const PixelIcon = memo(function PixelIcon({
  name,
  size = 24,
  title,
}: {
  name: PixelIconName;
  /** Rendered size in CSS px; multiples of 12 keep every art pixel whole. */
  size?: number;
  title?: string;
}) {
  let shape = CACHE.get(name);
  if (!shape) {
    shape = runs(ICONS[name]);
    CACHE.set(name, shape);
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      fill="currentColor"
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
    >
      {shape.map((run) => (
        <rect key={`${run.x}-${run.y}`} x={run.x} y={run.y} width={run.width} height={1} opacity={run.dim ? 0.45 : 1} />
      ))}
    </svg>
  );
});
